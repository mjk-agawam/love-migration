def read_csv(path):
    try:
        with open(path, newline='', encoding='utf-8') as f:
            return list(csv.DictReader(f))
    except FileNotFoundError:
        print(f"  ERROR: source file not found: {path}", file=sys.stderr)
        print(f"  Run Claude Code to regenerate source CSVs from Google Sheets.", file=sys.stderr)
        sys.exit(1)


def write_csv(path, fieldnames, rows):
    with open(path, 'w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)
    return len(rows)


def _load_creds():
    creds_path = '/tmp/claude-501/love_creds.json'
    with open(creds_path) as f:
        c = json.load(f)
    return c['accessToken'], c['instanceUrl']


def sf_query(soql):
    token, instance = _load_creds()
    url = f"{instance}/services/data/v66.0/query?q={urllib.parse.quote(soql)}"
    req = urllib.request.Request(url, headers={'Authorization': f'Bearer {token}'})
    with urllib.request.urlopen(req) as r:
        data = json.loads(r.read())
    records = data.get('records', [])
    # handle pagination
    next_url = data.get('nextRecordsUrl')
    while next_url:
        req2 = urllib.request.Request(
            f"{instance}{next_url}",
            headers={'Authorization': f'Bearer {token}'},
        )
        with urllib.request.urlopen(req2) as r2:
            page = json.loads(r2.read())
        records.extend(page.get('records', []))
        next_url = page.get('nextRecordsUrl')
    return records


def sf_upsert(sobject, ext_field, csv_path, dry_run):
    if dry_run:
        with open(csv_path, newline='', encoding='utf-8') as f:
            n = sum(1 for _ in csv.reader(f)) - 1
        print(f"    [DRY RUN] Would upsert {n} {sobject} records via {ext_field}")
        return True
    token, instance = _load_creds()
    base = f"{instance}/services/data/v66.0/jobs/ingest"

    # Create bulk ingest job
    job_body = json.dumps({
        'object': sobject,
        'externalIdFieldName': ext_field,
        'contentType': 'CSV',
        'operation': 'upsert',
        'lineEnding': 'CRLF',
    }).encode()
    req = urllib.request.Request(
        base,
        data=job_body,
        headers={'Authorization': f'Bearer {token}', 'Content-Type': 'application/json'},
    )
    with urllib.request.urlopen(req) as r:
        job = json.loads(r.read())
    job_id = job['id']

    # Upload CSV data
    with open(csv_path, 'rb') as f:
        csv_data = f.read()
    upload_url = f"{base}/{job_id}/batches"
    req2 = urllib.request.Request(
        upload_url,
        data=csv_data,
        method='PUT',
        headers={'Authorization': f'Bearer {token}', 'Content-Type': 'text/csv'},
    )
    urllib.request.urlopen(req2).close()

    # Close the job (triggers processing)
    close_body = json.dumps({'state': 'UploadComplete'}).encode()
    req3 = urllib.request.Request(
        f"{base}/{job_id}",
        data=close_body,
        method='PATCH',
        headers={'Authorization': f'Bearer {token}', 'Content-Type': 'application/json'},
    )
    urllib.request.urlopen(req3).close()

    # Poll until done
    for _ in range(240):
        time.sleep(3)
        req4 = urllib.request.Request(
            f"{base}/{job_id}",
            headers={'Authorization': f'Bearer {token}'},
        )
        with urllib.request.urlopen(req4) as r4:
            status = json.loads(r4.read())
        state = status.get('state', '')
        if state in ('JobComplete', 'Failed', 'Aborted'):
            break
    ok = status.get('numberRecordsProcessed', 0)
    failed = status.get('numberRecordsFailed', 0)
    print(f"    Successful records: {ok - failed}")
    print(f"    Failed records: {failed}")
    print(f"    Processed records: {ok}")
    if failed:
        print(f"    WARNING: {failed} failed records in job {job_id}", file=sys.stderr)
    return state == 'JobComplete' and failed == 0


def resolve_ext_ids(ext_ids):
    out = {}
    for i in range(0, len(ext_ids), 200):
        batch = ext_ids[i:i+200]
        ids_str = "','".join(e.replace("'", "\\'") for e in batch)
        recs = sf_query(
            f"SELECT Id, Account_External_ID__c FROM Account "
            f"WHERE Account_External_ID__c IN ('{ids_str}')"
        )
        for r in recs:
            out[r['Account_External_ID__c']] = r['Id']
    return out


