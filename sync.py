# ── Helpers ───────────────────────────────────────────────────────────────────

def slugify(text):
    t = unicodedata.normalize('NFKD', str(text).strip())
    t = t.encode('ascii', 'ignore').decode('ascii')
    return re.sub(r'[^a-z0-9]', '', t.lower())


def clean_amount(v):
    v = str(v).strip()
    if not v or v in ('-', '—', '–', '$0', '0'):
        return ''
    v = re.sub(r'[$,\s]', '', v)
    v = re.split(r'[-–—]', v)[0].strip()
    try:
        f = float(v)
        return str(int(f)) if f > 0 else ''
    except ValueError:
        return ''


def clean_email(raw):
    raw = str(raw).strip()
    if not raw:
        return ''
    for c in re.split(r'[\s;,\n|]+', raw):
        c = c.strip()
        if '@' in c and '.' in c.split('@')[-1] and 'not.given' not in c:
            return c.lower()
    return ''


def is_blank(v):
    return str(v).strip() in ('', '—', '–', '-', 'N/A', 'None', '#ERROR!', '#REF!')


def truncate(v, n):
    return str(v)[:n] if v else ''


def map_relationship(status):
    s = str(status).strip().lower()
    if s.startswith('submitted') or s.startswith('loi'):
        return 'Pending Funder'
    if s.startswith('ng') or 'declined' in s:
        return 'Declined Funding'
    if 'granted' in s or 'closed won' in s:
        return 'Funder'
    return 'Prospect'


def map_stage(status):
    s = str(status).strip().lower()
    if s.startswith('loi'):
        return 'LOI Submitted'
    if s.startswith('submitted'):
        return 'Application Submitted'
    if s.startswith('ng') or 'declined' in s:
        return 'Closed Lost'
    if 'granted' in s or 'closed won' in s:
        return 'Closed Won'
    return 'Prospecting'


def parse_close_date(text):
    s = str(text).strip()
    if not s or s in ('Rolling', 'Open year-round', 'N/A', '2026 TBD', 'Varies', 'TBD'):
        return '2026-12-31'
    MONTHS = {
        'january':'01','february':'02','march':'03','april':'04',
        'may':'05','june':'06','july':'07','august':'08',
        'september':'09','october':'10','november':'11','december':'12',
    }
    m = re.search(r'(January|February|March|April|May|June|July|August|'
                  r'September|October|November|December)\s+(\d{1,2}),?\s*(\d{4})', s, re.I)
    if m:
        return f"{m.group(3)}-{MONTHS[m.group(1).lower()]}-{int(m.group(2)):02d}"
    m = re.search(r'(\d{1,2})/(\d{1,2})/(\d{4})', s)
    if m:
        return f"{m.group(3)}-{int(m.group(1)):02d}-{int(m.group(2)):02d}"
    m = re.search(r'(January|February|March|April|May|June|July|August|'
                  r'September|October|November|December)\s+(\d{1,2})', s, re.I)
    if m:
        return f"2026-{MONTHS[m.group(1).lower()]}-{int(m.group(2)):02d}"
    m = re.search(r'(\d{1,2})/(\d{1,2})', s)
    if m:
        return f"2026-{int(m.group(1)):02d}-{int(m.group(2)):02d}"
    return '2026-12-31'


def year_from_header(header):
    h = re.sub(r'[$,]', '', str(header))
    m = re.search(r'(20\d{2})', h)
    return int(m.group(1)) if m else None


