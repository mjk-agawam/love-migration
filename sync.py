def load_existing_sf_ext_ids():
    """Return set of Account_External_ID__c values already in SF."""
    recs = sf_query(
        "SELECT Account_External_ID__c FROM Account "
        "WHERE Account_External_ID__c != null"
    )
    return {r['Account_External_ID__c'] for r in recs}


def build_p2_ext_id(name, existing_ids):
    """Generate external ID from name; if it collides, return existing match."""
    slug = slugify(name)
    if slug in existing_ids:
        return slug
    # Also check common variants with & and . stripped
    for existing in existing_ids:
        if slugify(existing) == slug:
            return existing
    return slug


