def load_by_date_enrichment():
    """Load MailChimp, Note data from source_indiv_by_date.csv.
    Returns: dict mapping email -> {mailchimp, note}
    """
    enrichment = {}
    try:
        rows = read_csv(f'{PROJ}/source_indiv_by_date.csv')
        for row in rows:
            email = clean_email(str(row.get('Email Address', '')))
            if not email:
                continue
            mailchimp = str(row.get('MailChimp?', '')).strip()
            note = str(row.get('Note', '')).strip()
            enrichment[email] = {'mailchimp': mailchimp, 'note': note}
    except FileNotFoundError:
        pass  # No enrichment file available yet
    return enrichment


def build_indiv(dry_run=False):
    accts, conts, opps = [], [], []
    seen_dedup = {}  # Maps dedup key -> ext_id
    created_ext_ids = set()  # Track ext_ids we've already created Account/Contact for

    # Load enrichment data (MailChimp, Note)
    enrichment = load_by_date_enrichment()

    # Pass 1: Collect all rows and find best email per person (name-based key)
    all_rows = []
    name_to_email = {}  # Maps name-based key -> best email if available
    for src_csv, prefix, cleanup_col, year_headers in INDIV_TAB_INFO:
        rows = read_csv(f'{PROJ}/{src_csv}')
        for row in rows:
            first = str(row.get('First Name','')).strip()
            last  = str(row.get('Last Name','')).strip()
            if not first and not last:
                continue
            if 'not shared' in first.lower() and 'not shared' in last.lower():
                continue
            if first in ('—','–') and last in ('—','–'):
                continue

            all_rows.append((first, last, row, year_headers))

            # Track email by name-based key (full name); prefer any email over none
            name_key = (slugify(first), slugify(last))
            email = clean_email(str(row.get(cleanup_col, '')))
            if not email:
                email = clean_email(str(row.get('Email Address', '')))
            if email and not name_to_email.get(name_key):
                name_to_email[name_key] = email

    # Pass 2: Process rows with consolidated dedup keys
    for first, last, row, year_headers in all_rows:
        cleanup_col = None
        for src_csv, prefix_tmp, col, _ in INDIV_TAB_INFO:
            if str(row.get(col, '')):
                cleanup_col = col
                break
        if not cleanup_col:
            cleanup_col = 'Email Address'

        email = clean_email(str(row.get(cleanup_col, '')))
        if not email:
            email = clean_email(str(row.get('Email Address', '')))

        # Use consolidated email if available for name-based dedup
        name_key = (slugify(first), slugify(last))
        if not email and name_key in name_to_email:
            email = name_to_email[name_key]

        # Dedup key: email takes priority (most reliable), else name-based
        if email:
            dedup_key = ('email', email)
            base = f"indiv_{slugify(email)}"
        else:
            dedup_key = ('name', slugify(first), slugify(last))
            base = f"indiv_{slugify(first)}{slugify(last)}"

        # Reuse ext_id if this person already exists (from earlier row)
        if dedup_key in seen_dedup:
            ext_id = seen_dedup[dedup_key]
        else:
            # Generate new ext_id; handle name collisions with suffix
            n = 1
            ext_id = base
            while ext_id in created_ext_ids:
                n += 1
                ext_id = f"{base}_{n}"
            seen_dedup[dedup_key] = ext_id

        # Only create Account/Contact once per ext_id
        if ext_id not in created_ext_ids:
            household = f"{last} Household" if last else f"{first} Household"
            accts.append({
                'Account_External_ID__c': ext_id,
                'Name': household,
                'RecordTypeId': RT_HOUSEHOLD,
                'Relationship__c': 'Funder',
            })
            # Enrich contact with MailChimp and Note data if available
            cont_data = {
                'Contact_External_ID__c': ext_id,
                'FirstName': first,
                'LastName':  last if not is_blank(last) else first,
                'Email':     email,
                '_ext': ext_id,
            }
            if email in enrichment:
                mailchimp = enrichment[email].get('mailchimp', '')
                note = enrichment[email].get('note', '')
                if mailchimp:
                    cont_data['MailChimp_Status__c'] = mailchimp
                if note:
                    cont_data['Note__c'] = note
            conts.append(cont_data)
            created_ext_ids.add(ext_id)

        # Create Opportunities for each donation year
        full = f"{first} {last}".strip()
        year_amounts = {}  # Track amounts per year to handle duplicates
        for hdr in year_headers:
            year = year_from_header(hdr)
            if not year:
                continue
            amt = clean_amount(row.get(hdr, ''))
            if not amt:
                continue

            # Count occurrences of this amount in this year for this donor
            year_key = (year, amt)
            if year_key not in year_amounts:
                year_amounts[year_key] = 0
            year_amounts[year_key] += 1
            seq = year_amounts[year_key]

            # Ext ID includes amount; add sequence if multiple same-amount donations
            if seq == 1:
                opp_ext_id = f"{ext_id}_donation_{year}_{amt}"
            else:
                opp_ext_id = f"{ext_id}_donation_{year}_{amt}_{seq}"

            opps.append({
                'Opportunity_External_ID__c': opp_ext_id,
                'Name':      truncate(f"{full} Donation {year}", 120),
                'StageName': 'Closed Won',
                'CloseDate': f"{year}-12-31",
                'Amount':    amt,
                '_ext': ext_id,
            })

    return accts, conts, opps


